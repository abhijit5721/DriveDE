// Generates src/narratorTimings.ts from the actual narration WAV durations.
// Run after vo-narrator/<lang>/s1..s7.wav exist: node scripts/gen-narrator-timings.mjs en
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const lang = process.argv[2] ?? 'en';
const FPS = 30;
const GAP = 10; // frames of breathing room after each segment
const durations = [];
for (let i = 1; i <= 7; i++) {
  const out = execSync(
    `ffprobe -v error -show_entries format=duration -of csv=p=0 public/vo-narrator/${lang}/s${i}.wav`
  ).toString().trim();
  durations.push(parseFloat(out));
}
const frames = durations.map((d) => Math.ceil(d * FPS) + GAP);
const starts = [];
let acc = 0;
for (const f of frames) { starts.push(acc); acc += f; }
const body = `// AUTO-GENERATED by scripts/gen-narrator-timings.mjs (${lang}). Do not edit.
export const NARR_FPS = ${FPS};
export const NARR_SEG_FRAMES = ${JSON.stringify(frames)} as const;
export const NARR_SEG_STARTS = ${JSON.stringify(starts)} as const;
export const NARR_SPEECH_FRAMES = ${acc};
export const NARR_END_CARD_FRAMES = 80;
export const NARR_TOTAL_FRAMES = ${acc} + 80;
`;
writeFileSync('src/narratorTimings.ts', body);
console.log('segments (s):', durations.map((d) => d.toFixed(2)).join(', '));
console.log('total:', ((acc + 80) / FPS).toFixed(1) + 's');
